#!/usr/bin/env node
// Builds feedback/src/legal.ts (static /privacy and /terms pages on bud-feedback) from docs/privacy.md and
// docs/terms.md. Small Markdown subset: #/## headings, paragraphs, "- " and "1. " lists (one nesting level by
// two-space indent), **bold**, `code`, and bare https URLs / emails as links. `--check` fails if legal.ts is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const inline = s => esc(s)
  .replace(/`([^`]+)`/g, '<code>$1</code>')
  .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
  .replace(/(https:\/\/[^\s<)]+[^\s<).,;])/g, '<a href="$1">$1</a>')
  .replace(/\b([a-z0-9._-]+@[a-z0-9-]+\.[a-z.]+[a-z])\b/gi, '<a href="mailto:$1">$1</a>');

export function mdToHtml(md) {
  const out = [];
  const blocks = md.replace(/\r/g, '').split(/\n{2,}/);
  for (let raw of blocks) {
    let lines = raw.split('\n');
    if (!raw.trim()) continue;
    // A heading may be followed directly by text (no blank line): emit it, then treat the rest as its own block.
    const lead = lines[0].match(/^(#{1,3}) (.+)$/);
    if (lead && lines.length > 1) { out.push(`<h${lead[1].length}>${inline(lead[2])}</h${lead[1].length}>`); lines = lines.slice(1); raw = lines.join('\n'); }
    const h = raw.match(/^(#{1,3}) (.+)$/);
    if (h && lines.length === 1) { const n = h[1].length; out.push(`<h${n}>${inline(h[2])}</h${n}>`); continue; }
    if (/^(\s{0,2})(- |\d+\. )/.test(lines[0])) {
      // list block: items start with "- " or "N. " (indent 0 = outer, indent 2 = nested); other lines continue.
      const items = [];
      for (const l of lines) {
        const m = l.match(/^(\s*)(- |\d+\. )(.*)$/);
        if (m) items.push({ depth: m[1].length >= 2 ? 1 : 0, ordered: m[2] !== '- ', text: m[3] });
        else items[items.length - 1].text += ' ' + l.trim();
      }
      const base = items[0].depth;
      let html = ''; const stack = [];
      for (const it of items) {
        const d = it.depth - base;
        while (stack.length > d + 1) html += `</li></${stack.pop()}>`;
        if (stack.length < d + 1) { const t = it.ordered ? 'ol' : 'ul'; stack.push(t); html += `<${t}><li>`; }
        else html += '</li><li>';
        html += inline(it.text);
      }
      while (stack.length) html += `</li></${stack.pop()}>`;
      out.push(html);
      continue;
    }
    out.push(`<p>${inline(lines.map(l => l.trim()).join(' '))}</p>`);
  }
  return out.join('\n');
}

const page = (title, body) => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>body{font:16px/1.55 -apple-system,system-ui,sans-serif;max-width:720px;margin:0 auto;padding:24px 18px 64px;color:#e8f2ec;background:#0b1410}h1{font-size:26px;line-height:1.25}h2{font-size:19px;margin-top:28px}a{color:#3ddc84}code{background:#16261d;padding:1px 5px;border-radius:4px}nav{font-size:14px;margin-bottom:20px}</style>
</head><body><nav><a href="/privacy">Privacy</a> · <a href="/terms">Terms</a></nav>
${body}
</body></html>`;

export function buildLegal() {
  const priv = readFileSync(join(root, 'docs/privacy.md'), 'utf8');
  const terms = readFileSync(join(root, 'docs/terms.md'), 'utf8');
  return `// GENERATED by scripts/build-legal.mjs from docs/privacy.md and docs/terms.md. Do not edit by hand.
export const LEGAL_CSP = "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";
export const PRIVACY_HTML = ${JSON.stringify(page('BUD (Bots Up Display) Privacy Policy', mdToHtml(priv)))};
export const TERMS_HTML = ${JSON.stringify(page('BUD (Bots Up Display) Terms of Use', mdToHtml(terms)))};
`;
}

const target = join(root, 'feedback/src/legal.ts');
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const next = buildLegal();
  if (process.argv.includes('--check')) {
    let cur = ''; try { cur = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (cur !== next) { console.error('feedback/src/legal.ts is stale: run node scripts/build-legal.mjs'); process.exit(1); }
    console.log('OK: legal pages match docs');
  } else { writeFileSync(target, next); console.log(`Wrote ${target}`); }
}
